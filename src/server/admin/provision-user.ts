import "server-only";

import { createHash, randomBytes } from "node:crypto";
import { Prisma } from "@prisma/client";
import { z } from "zod";

import { prisma } from "@/server/db/prisma";
import type { AdminSessionContext } from "@/server/admin/admin-auth";
import { hashPassword } from "@/server/auth/password";
import { sendAccountActivationMail } from "@/server/mail/resend-mailer";

// No role, password, token or arbitrary organization ID is accepted from the client.
export const provisionUserSchema = z.object({
  fullName: z.string().trim().min(2).max(120),
  email: z.string().trim().toLowerCase().max(254).pipe(z.email()),
  companyName: z.string().trim().min(2).max(120),
}).strict();

export class UserProvisioningError extends Error {
  constructor(public code: string, message: string, public status: number) {
    super(message);
  }
}

function activationOrigin(value: string | undefined) {
  try {
    const url = new URL(value ?? "");
    const localHttp = process.env.NODE_ENV !== "production" && url.protocol === "http:" &&
      ["localhost", "127.0.0.1"].includes(url.hostname);
    if ((!localHttp && url.protocol !== "https:") || url.username || url.password || url.search || url.hash || url.pathname !== "/") throw new Error();
    return url.origin;
  } catch {
    throw new UserProvisioningError("ACTIVATION_URL_MISSING", "Geçerli APP_URL yapılandırılmadan hesap oluşturulamaz.", 503);
  }
}

export async function provisionManagedUser(input: {
  account: z.infer<typeof provisionUserSchema>;
  session: AdminSessionContext;
  ipAddress?: string | null;
  userAgent?: string | null;
}, dependencies = { client: prisma, sendMail: sendAccountActivationMail, appUrl: process.env.APP_URL }) {
  const account = provisionUserSchema.parse(input.account);
  const origin = activationOrigin(dependencies.appUrl);
  const token = randomBytes(32).toString("hex");
  const tokenHash = createHash("sha256").update(token).digest("hex");
  const expiresAt = new Date(Date.now() + 60 * 60 * 1000);
  // Nobody receives this random password. Only the email holder can set a usable one.
  const passwordHash = hashPassword(randomBytes(48).toString("hex"));

  let created;
  try {
    created = await dependencies.client.$transaction(async (tx) => {
      const existing = await tx.user.findFirst({
        where: { email: { equals: account.email, mode: "insensitive" } }, select: { id: true },
      });
      if (existing) throw new UserProvisioningError("EMAIL_TAKEN", "Bu e-posta için hesap zaten var. Mevcut hesabı kullanın; parola kurtarma ile erişim sağlanabilir.", 409);
      const organization = await tx.organization.create({
        data: {
          name: account.companyName,
          slug: `workspace-${randomBytes(12).toString("hex")}`,
          plan: "Managed Workspace", region: "Kurulum bekleniyor", cloudMode: "hybrid_cloud",
          complianceFrameworks: [], demoMode: false, onboardingCompleted: false,
          settings: { create: { region: "Kurulum bekleniyor", cloudMode: "hybrid_cloud", complianceFrameworks: [] } },
          riskPolicy: { create: {
            criticalClassificationWeight: 24, missingEncryptionWeight: 18, publicCloudSensitiveWeight: 16,
            missingBackupWeight: 10, noKmsWeight: 12, openCriticalEventWeight: 14, deceptionTriggerWeight: 20,
          } },
          reportBranding: { create: {
            companyName: account.companyName, reportFooter: "Generated by Hybrid Cloud Security Console",
            preparedByLabel: "Prepared by HCSC", confidentialityLabel: "Internal / Confidential",
          } },
        },
      });
      const user = await tx.user.create({
        data: {
          name: account.fullName, email: account.email, passwordHash,
          role: "security_admin", platformRole: "USER", status: "active", mfaEnabled: false,
          avatarInitials: account.fullName.split(/\s+/).slice(0, 2).map((part) => part[0].toUpperCase()).join(""),
          memberships: { create: { organizationId: organization.id, role: "security_admin" } },
          passwordResetTokens: { create: { tokenHash, expiresAt } },
        },
        select: { id: true, name: true, email: true },
      });
      await tx.auditLog.create({ data: {
        organizationId: input.session.organizationId, userId: input.session.userId,
        actorName: input.session.user.name, actorRole: input.session.user.role,
        action: "admin_user_provisioned", module: "Admin", target: user.id,
        result: "success", severity: "info",
        details: "Yeni müşteri hesabı ve boş çalışma alanı oluşturuldu; parola belirleme ve gerçek MFA kurulumu bekleniyor.",
        ipAddress: input.ipAddress, device: input.userAgent,
        metadata: { provisionedOrganizationId: organization.id, platformRole: "USER" },
      } });
      return { user, organizationId: organization.id };
    });
  } catch (error) {
    if (error instanceof Prisma.PrismaClientKnownRequestError && error.code === "P2002") {
      throw new UserProvisioningError("ACCOUNT_CONFLICT", "Hesap oluşturma çakışması. Kullanıcı listesini kontrol edin.", 409);
    }
    throw error;
  }

  const delivery = await dependencies.sendMail({
    to: created.user.email, recipientName: created.user.name, organizationName: account.companyName,
    resetUrl: `${origin}/reset-password?token=${token}`,
  }).catch(() => ({ success: false, reason: "delivery-failed" as const }));

  // No raw token, password hash or setup URL is exposed, including in development.
  return {
    userId: created.user.id, organizationId: created.organizationId, email: created.user.email,
    activationDelivery: delivery.success ? "accepted_by_provider" as const : "failed" as const,
    message: delivery.success
      ? "Hesap oluşturuldu. Parola belirleme e-postası gönderim sağlayıcısına iletildi; teslim durumu henüz doğrulanmadı."
      : "Hesap oluşturuldu ancak e-posta gönderilemedi. Mail yapılandırmasını kontrol edin; kullanıcı Şifremi unuttum üzerinden yeni bağlantı isteyebilir. Hesabı yeniden oluşturmayın.",
  };
}
